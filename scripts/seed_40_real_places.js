// Helper to calculate rating Average and review count
function processPlace(p, index) {
  const avg = Number((p.reviews.reduce((s, r) => s + r.rating, 0) / p.reviews.length).toFixed(1));
  const mappedReviews = p.reviews.map((r, i) => ({
    reviewId: `rev-${p.slug}-${i + 1}`,
    authorName: r.author,
    authorAvatar: `https://images.unsplash.com/photo-${1535713875000 + ((index * 13 + i * 7) % 500)}?w=150`,
    rating: r.rating,
    content: r.content,
    createdAt: new Date(r.date).toISOString(),
    isGoogleReview: true,
    likes: [],
    comments: []
  }));

  return {
    id: `place-${p.slug}`,
    name: p.name,
    slug: p.slug,
    description: p.description,
    categoryName: p.categoryName,
    catSlug: p.catSlug,
    address: {
      street: p.street,
      ward: p.district,
      district: p.district,
      city: p.city,
      provinceCode: p.provinceCode
    },
    location: {
      type: "Point",
      coordinates: p.coordinates
    },
    images: [{ url: p.imageUrl, isCover: true, publicId: `places/${p.slug}` }],
    status: "active",
    ratingAverage: avg,
    reviewCount: p.reviews.length,
    googleRating: p.googleRating,
    googleReviewCount: p.googleReviewCount,
    googleReviewSnippet: p.googleReviewSnippet,
    openingHours: p.openingHours,
    ticketPrice: p.ticketPrice,
    ticketType: p.ticketType,
    isOpenNow: true,
    reviews: mappedReviews,
    createdAt: new Date(),
    updatedAt: new Date()
  };
}

async function main() {
  console.log(`[SEED-40] Chuẩn bị bộ dữ liệu gồm ${rawPlaces.length} địa điểm thực tế...`);
  const processed = rawPlaces.map((p, idx) => processPlace(p, idx));

  // 1. Ghi ra file frontend data để frontend có dữ liệu offline hoàn hảo
  const frontendDataPath = path.resolve(__dirname, '../frontend/src/data/realPlacesData.js');
  const dir = path.dirname(frontendDataPath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

  const exportContent = `// Bộ dữ liệu 42 địa điểm thực tế tại TP.HCM & các tỉnh lân cận với dữ liệu Google Maps & đánh giá thật\nexport const REAL_PLACES_DATA = ${JSON.stringify(processed, null, 2)};\n`;
  fs.writeFileSync(frontendDataPath, exportContent, 'utf-8');
  console.log(`[SEED-40] Đã tạo file frontend: ${frontendDataPath}`);

  // 2. Kết nối MongoDB Atlas và upsert toàn bộ 42 địa điểm vào collection 'places'
  const client = new MongoClient(uri);
  try {
    await client.connect();
    console.log('[SEED-40] Đã kết nối thành công tới MongoDB Atlas!');
    const db = client.db(dbName);

    // Lấy mapping categoryId nếu có
    const cats = await db.collection('categories').find({}).toArray();
    const catMap = {};
    cats.forEach(c => { catMap[c.slug] = c._id; });

    // Xóa dữ liệu places cũ để cập nhật bộ 42 địa điểm mới chuẩn chỉnh
    console.log('[SEED-40] Cập nhật / Upsert 42 địa điểm vào MongoDB Atlas collection "places"...');
    
    for (const place of processed) {
      const doc = {
        name: place.name,
        slug: place.slug,
        description: place.description,
        categoryId: catMap[place.catSlug] || new ObjectId('650000000000000000000003'),
        address: place.address,
        location: place.location,
        images: place.images,
        status: "active",
        ratingAverage: place.ratingAverage,
        reviewCount: place.reviewCount,
        googleRating: place.googleRating,
        googleReviewCount: place.googleReviewCount,
        googleReviewSnippet: place.googleReviewSnippet,
        openingHours: place.openingHours,
        ticketPrice: place.ticketPrice,
        ticketType: place.ticketType,
        reviews: place.reviews.map(r => ({
          reviewId: new ObjectId(),
          authorName: r.authorName,
          authorAvatar: r.authorAvatar,
          rating: r.rating,
          content: r.content,
          createdAt: new Date(r.createdAt),
          isGoogleReview: true,
          likes: [],
          comments: []
        })),
        createdAt: new Date(),
        updatedAt: new Date()
      };

      await db.collection('places').updateOne(
        { slug: place.slug },
        { $set: doc },
        { upsert: true }
      );
    }

    const totalCount = await db.collection('places').countDocuments();
    console.log(`[SEED-40] === THÀNH CÔNG! Tổng số địa điểm thực tế trên Atlas hiện tại: ${totalCount} ===`);
  } catch (err) {
    console.error('[SEED-40] Lỗi khi seed database:', err);
  } finally {
    await client.close();
  }
}

main();
